from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class LineOrderStatus(str, Enum):
    pending = 'pending'
    effective = 'effective'
    voided = 'voided'
    reversing = 'reversing'
    reversed = 'reversed'
class HandoverSide(str, Enum):
    from_line = 'from'
    to_line = 'to'
